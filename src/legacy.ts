import { mkdir, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { JSDOM } from 'jsdom';
import { digest, escapeHtml, htmlText, loadStory, normalizeText, sanitizeHtml } from './content.js';
import { assertInside, checkedRoot, containedPath, findContentFolders, readContained } from './safe-path.js';
import {readImage,thumbnailInFolder} from './images.js';

export interface ImportResult { source: string; output?: string; status: 'ready' | 'needs_review'; chapters?: number; edits?: string[]; error?: string }
/** Explicit legacy conversion: metadata is copied from labelled fields, never generated by AI. */
export async function importLegacy(input: string, output: string): Promise<ImportResult[]> {
  const folders = await findContentFolders(input);
  const inputRoot = await checkedRoot(input);
  const destination = path.resolve(output);
  // Conversion always uses a separate directory; neither ancestor may contain the other.
  for (const root of [inputRoot, ...folders]) {
    for (const [a,b] of [[root,destination],[destination,root]]) {
      const relative = path.relative(a!, b!);
      if (!relative || relative !== '..' && !relative.startsWith(`..${path.sep}`) && !path.isAbsolute(relative)) {
        throw new Error('--out phải là folder riêng, ngoài cây nguồn.');
      }
    }
  }
  await mkdir(destination, { recursive: true });
  const targetRoot = await checkedRoot(destination);
  if ((await readdir(targetRoot)).length) throw new Error('--out phải trống; không ghi đè bản import cũ.');
  const results: ImportResult[] = [];
  for (const [index,folder] of folders.entries()) {
    const result: ImportResult = { source: folder, status: 'needs_review' };
    results.push(result);
    try {
      const info = await readContained(folder, 'info.txt');
      const originalHtml = await readContained(folder, 'article_seo_ready.html');
      const thumbnail=await thumbnailInFolder(folder);
      const lines = info.split(/\r?\n/);
      const field = (label: string): string => {
        const matches = lines.map((v,i) => v.includes(label) ? i : -1).filter(i => i >= 0);
        if (matches.length !== 1 || !lines[matches[0]! + 1]?.trim()) throw new Error(`Thiếu/trùng field ${label}`);
        return lines[matches[0]! + 1]!.trim();
      };
      const titles = [...info.matchAll(/^Chương (\d+): (.+)$/gm)].map(m => ({ order: Number(m[1]), title: m[2]!.trim() }));
      if (!titles.length || titles.some((v,i)=>v.order!==i+1)) throw new Error('Tiêu đề chương phải khai báo liên tục từ 1.');
      const files = (await readdir(folder)).filter(f=>/^chapter_\d+\.txt$/i.test(f));
      if (files.length !== titles.length) throw new Error('Số TXT không khớp danh sách chương info.txt.');
      const doc = new JSDOM(originalHtml).window.document;
      if (doc.querySelector('script,iframe,object,embed,form,base') || [...doc.querySelectorAll('*')].some(e=>[...e.attributes].some(a=>/^on/i.test(a.name)))) throw new Error('Nguồn HTML chứa active content.');
      if (doc.querySelectorAll('[id^="chapter-"]').length !== titles.length) throw new Error('Số section HTML không khớp info.txt.');
      const edits: string[] = [];
      const sourceHashes: Record<string,string> = { 'info.txt': digest(info), 'article_seo_ready.html': digest(originalHtml) };
      const chapters: { order: number; title: string; html: string; text: string }[] = [];
      for (const entry of titles) {
        const sections = doc.querySelectorAll(`[id="chapter-${entry.order}"]`);
        if (sections.length !== 1) throw new Error(`Section ${entry.order} thiếu/trùng.`);
        const section = sections[0]!;
        const heading = section.querySelector('h1,h2');
        if (!heading || normalizeText(heading.textContent ?? '') !== normalizeText(entry.title)) throw new Error(`Chương ${entry.order}: heading không khớp info.txt.`);
        heading.remove();
        const filename = `chapter_${entry.order}.txt`;
        const raw = await readContained(folder,filename);
        sourceHashes[filename] = digest(raw);
        const clean = (value: string, log = false): string => {
          let body = value.trim();
          while (true) {
            const prefix = body.match(/^(.{1,300}?)\s*009\s+/);
            if (!prefix) break;
            const candidate = prefix[1]!.trim();
            // Known crawler title noise: exact title, or one accidentally doubled character.
            // This never edits prose: the entire prefix must be the title followed by marker 009.
            const exact = candidate === entry.title;
            const doubled = candidate.length === entry.title.length + 1 && [...candidate].some((char,i) =>
              i > 0 && char === candidate[i-1] && candidate.slice(0,i) + candidate.slice(i+1) === entry.title);
            if (!exact && !doubled) break;
            body = body.slice(prefix[0].length);
            if (log) edits.push(`Chương ${entry.order}: bỏ tiêu đề lặp${doubled ? ' có một ký tự lặp' : ''} + 009 ở đầu.`);
          }
          if (/Comments\s+0\s*$/.test(body)) {
            body = body.replace(/\s*Comments\s+0\s*$/,'').trimEnd();
            if (log) edits.push(`Chương ${entry.order}: bỏ Comments 0 ở cuối.`);
          }
          return body;
        };
        const text = clean(raw,true);
        const first = section.querySelector('p');
        if (first && clean(first.textContent ?? '') !== (first.textContent ?? '').trim()) first.textContent = clean(first.textContent ?? '');
        const last = [...section.querySelectorAll('p')].at(-1);
        if (last && /Comments\s+0\s*$/.test(last.textContent ?? '')) {
          last.textContent = (last.textContent ?? '').replace(/\s*Comments\s+0\s*$/,'');
          if (!last.textContent.trim()) last.remove();
        }
        const html = sanitizeHtml(section.innerHTML);
        if (htmlText(html) !== normalizeText(text)) throw new Error(`Chương ${entry.order}: HTML/TXT khác nhau sau làm sạch; không tự đoán.`);
        chapters.push({ ...entry, html, text });
      }
      const keywords = field('Focus & Secondary Keywords').split(',').map(s=>s.trim()).filter(Boolean);
      const category = field('Category');
      const metadata = {
        story_title: titles[0]!.title, source_url: null,
        source_id: `local-sha256:${digest(JSON.stringify(chapters.map(c=>normalizeText(c.text))))}`,
        intro: null, status: 'ready', issues: [],
        seo: { seo_title: field('SEO Title'), meta_description: field('Meta Description'), focus_keyword: keywords[0] ?? '',
          secondary_keywords: keywords.slice(1), categories: category === 'Biker Stories & Heartwarming Life Lessons' ? ['Biker Stories','Heartwarming Life Lessons'] : [category],
          tags: field('Tags').split(',').map(s=>s.trim()).filter(Boolean) },
        chapters: chapters.map(c=>({order:c.order,chapter_title:c.title,content_file:`chapter_${c.order}.txt`}))
      };
      const relative = `${index+1}/content`;
      const target = await containedPath(targetRoot,`${relative}/metadata.json`,true);
      const converted = path.dirname(target); assertInside(targetRoot,converted);
      await writeFile(target,JSON.stringify(metadata,null,2),{flag:'wx'});
      for (const c of chapters) await writeFile(await containedPath(targetRoot,`${relative}/chapter_${c.order}.txt`),c.text,{flag:'wx'});
      const html = chapters.map(c=>`<section id="chapter-${c.order}"><h2>${escapeHtml(c.title)}</h2>${c.html}</section>`).join('\n');
      await writeFile(await containedPath(targetRoot,`${relative}/article_seo_ready.html`),html,{flag:'wx'});
      if(thumbnail) {
        const current=await readImage(thumbnail.file);
        if(current.image.sha256!==thumbnail.sha256)throw new Error('Thumbnail thay đổi trong lúc import.');
        await writeFile(await containedPath(targetRoot,`${relative}/Thumbnail.jpg`),current.buffer,{flag:'wx'});
        edits.push('Sao chép Thumbnail.jpg vào bản import, giữ nguyên ảnh nguồn.');
      }
      await writeFile(await containedPath(targetRoot,`${relative}/import_report.json`),JSON.stringify({source:folder,sourceHashes,featuredImage:thumbnail,edits,sourceUrlKnown:false},null,2),{flag:'wx'});
      const validated = await loadStory(converted);
      if (!validated.ready) throw new Error(validated.issues.filter(i=>i.level==='error').map(i=>i.message).join('; '));
      Object.assign(result,{output:converted,status:'ready',chapters:chapters.length,edits});
    } catch (error) { result.error = (error as Error).message; }
  }
  await writeFile(await containedPath(targetRoot,'import_report.json'),JSON.stringify(results,null,2),{flag:'wx'});
  return results;
}
